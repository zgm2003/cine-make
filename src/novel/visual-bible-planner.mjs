import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const TIERS = ['S', 'A', 'B', 'C']

export async function planVisualBible({ runDir, maxSTier = 4 }) {
  if (!runDir) throw new Error('planVisualBible requires runDir')
  if (!Number.isInteger(maxSTier) || maxSTier < 1) {
    throw new Error('maxSTier must be a positive integer')
  }

  const charactersPath = join(runDir, 'bible', 'characters.json')
  const characters = await readCharacters(charactersPath)
  const plannedCharacters = characters.map(normalizeCharacter)
  const warnings = []
  const sTierCount = plannedCharacters.filter((character) => character.tier === 'S').length
  if (sTierCount > maxSTier) {
    warnings.push(`S-tier character count ${sTierCount} exceeds max ${maxSTier}; review visual budget before requesting image work.`)
  }

  const visualBibleDir = join(runDir, 'visual-bible')
  await mkdir(visualBibleDir, { recursive: true })

  const referencePlanPath = join(visualBibleDir, 'character-reference-plan.md')
  const triviewPromptsPath = join(visualBibleDir, 'character-triview-prompts.md')

  await writeFile(referencePlanPath, `${composeReferencePlan({ characters: plannedCharacters, warnings, maxSTier })}\n`, 'utf8')
  await writeFile(triviewPromptsPath, `${composePromptPlan(plannedCharacters)}\n`, 'utf8')

  return {
    referencePlanPath,
    triviewPromptsPath,
    counts: countCharacters(plannedCharacters),
    warnings
  }
}

async function readCharacters(charactersPath) {
  let raw
  try {
    raw = await readFile(charactersPath, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') {
      throw new Error(`Missing novel character bible: ${charactersPath}`)
    }
    throw error
  }

  let characters
  try {
    characters = JSON.parse(raw)
  } catch (error) {
    throw new Error(`Malformed novel character bible: ${charactersPath} must be valid JSON`)
  }

  if (!Array.isArray(characters)) {
    throw new Error(`Malformed novel character bible: ${charactersPath} must contain an array`)
  }

  return characters
}

function normalizeCharacter(character, index) {
  if (!character || typeof character !== 'object') {
    throw new Error(`Malformed novel character bible: character ${index + 1} must be an object`)
  }
  if (typeof character.name !== 'string' || !character.name.trim()) {
    throw new Error(`Malformed novel character bible: character ${index + 1} must have a name`)
  }

  const appearanceCount = normalizeCount(character.appearanceCount)
  const roleSignals = normalizeStringArray(character.roleSignals)
  const visualHints = normalizeStringArray(character.visualHints)
  const relationshipHints = normalizeStringArray(character.relationshipHints)
  const chapters = normalizeStringArray(character.chapters)
  const tier = normalizeTier(character.recommendedTier ?? character.tier) ?? inferTier({ appearanceCount, roleSignals })

  return {
    name: character.name.trim(),
    firstChapter: typeof character.firstChapter === 'string' ? character.firstChapter.trim() : '',
    appearanceCount,
    roleSignals,
    visualHints,
    relationshipHints,
    chapters,
    tier
  }
}

function normalizeTier(value) {
  if (typeof value !== 'string') return null
  const tier = value.trim().toUpperCase()
  return TIERS.includes(tier) ? tier : null
}

function inferTier({ appearanceCount, roleSignals }) {
  const roleText = roleSignals.join(' ').toLowerCase()
  if (/protagonist|main character|lead|主角|男主|女主/u.test(roleText) || appearanceCount >= 5) {
    return 'S'
  }
  if (/antagonist|villain|mentor|ally|investigator|反派|导师|同伴|搭档|关键/u.test(roleText) && appearanceCount >= 2) {
    return 'A'
  }
  if (appearanceCount >= 2) {
    return 'B'
  }
  return 'C'
}

function normalizeCount(value) {
  const count = Number(value)
  return Number.isFinite(count) && count > 0 ? count : 0
}

function normalizeStringArray(value) {
  if (!Array.isArray(value)) return []
  return value
    .filter((item) => typeof item === 'string')
    .map((item) => item.trim())
    .filter(Boolean)
}

function countCharacters(characters) {
  const counts = {
    characters: characters.length,
    S: 0,
    A: 0,
    B: 0,
    C: 0,
    imagePromptCharacters: 0
  }

  for (const character of characters) {
    counts[character.tier] += 1
    if (character.tier === 'S' || character.tier === 'A') {
      counts.imagePromptCharacters += 1
    }
  }

  return counts
}

function composeReferencePlan({ characters, warnings, maxSTier }) {
  const lines = [
    '# Character Reference Plan',
    '',
    '## Policy Notes',
    '- Visual bible planning only. No image files are generated by this planner.',
    '- S-tier characters receive tri-view and expression sheet prompts for later review.',
    '- A-tier characters receive front-view prompts for later review.',
    '- B-tier and C-tier characters keep text visual anchor only notes.',
    `- Suggested S-tier cap: ${maxSTier}.`,
    ''
  ]

  if (warnings.length) {
    lines.push('## Warnings')
    for (const warning of warnings) {
      lines.push(`- ${warning}`)
    }
    lines.push('')
  }

  for (const tier of TIERS) {
    lines.push(`## ${tier}-Tier`)
    const tierCharacters = characters.filter((character) => character.tier === tier)
    if (!tierCharacters.length) {
      lines.push('- none', '')
      continue
    }

    for (const character of tierCharacters) {
      lines.push(`### ${character.name}`)
      lines.push(`- Appearances: ${character.appearanceCount}`)
      lines.push(`- First chapter: ${character.firstChapter || 'unknown'}`)
      lines.push(`- Chapters: ${character.chapters.length ? character.chapters.join(', ') : 'unknown'}`)
      lines.push(`- Role signals: ${character.roleSignals.length ? character.roleSignals.join(', ') : 'none'}`)
      lines.push(`- Visual anchors: ${character.visualHints.length ? character.visualHints.join(', ') : 'none'}`)
      lines.push(`- Relationship anchors: ${character.relationshipHints.length ? character.relationshipHints.join(', ') : 'none'}`)
      if (tier === 'S') {
        lines.push('- Image planning: tri-view prompt, expression sheet prompt, costume/prop lock notes.')
      } else if (tier === 'A') {
        lines.push('- Image planning: front-view prompt, expression and costume notes.')
      } else {
        lines.push('- Image planning: text visual anchor only; no image prompt.')
      }
      lines.push('')
    }
  }

  return lines.join('\n').trimEnd()
}

function composePromptPlan(characters) {
  const lines = [
    '# Character Tri-View Prompts',
    '',
    'Only S-tier and A-tier characters are included here. This file is a text plan and does not generate images.'
  ]

  const promptCharacters = characters.filter((character) => character.tier === 'S' || character.tier === 'A')
  if (!promptCharacters.length) {
    lines.push('', '- none')
    return lines.join('\n')
  }

  for (const character of promptCharacters) {
    lines.push('', `## ${character.name} (${character.tier}-Tier)`)
    if (character.tier === 'S') {
      lines.push(`- Tri-view prompt: tri-view character reference sheet for ${character.name}; front, side, and back views; consistent face, hairstyle, body proportions, silhouette, and color palette; visual anchors: ${formatList(character.visualHints)}.`)
      lines.push(`- Expression sheet prompt: expression sheet for ${character.name}; neutral, alert, fearful, determined, and exhausted expressions; maintain identity and hairstyle; role context: ${formatList(character.roleSignals)}.`)
      lines.push(`- Costume/prop lock notes: preserve recurring wardrobe, key props, scars, accessories, and color accents from anchors: ${formatList(character.visualHints)}.`)
    } else {
      lines.push(`- Front-view prompt: front-view character reference for ${character.name}; consistent portrait and full-body silhouette; visual anchors: ${formatList(character.visualHints)}.`)
      lines.push(`- Expression/costume notes: keep a small expression set and stable costume cues; role context: ${formatList(character.roleSignals)}.`)
    }
  }

  return lines.join('\n')
}

function formatList(values) {
  return values.length ? values.join(', ') : 'none specified'
}
