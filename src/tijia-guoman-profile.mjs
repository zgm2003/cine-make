const DEFAULT_TIJIA_STYLE = '3D国漫，国风仙侠，偏水墨+古风写实结合，镜头节奏前紧后缓，强烈戏剧张力'

export function isTijiaGuomanSource(sourceText = '') {
  const text = String(sourceText)
  return /许怡宁/u.test(text)
    && /许悠然/u.test(text)
    && /江凡/u.test(text)
    && /(许正言|许父)/u.test(text)
    && /(三尺青锋|青锋|青剑)/u.test(text)
}

export function tijiaGuomanStyle(style) {
  const clean = String(style || '').trim()
  if (!clean) return DEFAULT_TIJIA_STYLE
  if (/3D国漫|国漫|水墨|仙侠/u.test(clean)) return clean
  return `${DEFAULT_TIJIA_STYLE}，${clean}`
}

