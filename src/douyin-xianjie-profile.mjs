const DEFAULT_STYLE = '3D国漫，国风仙侠，轻喜剧反差，古风写实材质，魔门阴冷压迫与短视频霓虹界面反差，角色表演克制但喜剧节奏明确'
const MULTI_CHAPTER_ERROR = '抖音仙界内容跨多个章节，请按章节分别生成 Seedance feed'

function compact(value) {
  return String(value ?? '').replace(/\s+/gu, ' ').trim()
}

function explicitChapterNumbers(sourceText = '') {
  return [...String(sourceText).matchAll(/第([123])章/gu)].map((match) => Number(match[1]))
}

export function assertDouyinXianjieSingleChapterSource(sourceText = '') {
  const chapters = [...new Set(explicitChapterNumbers(sourceText))]
  if (chapters.length > 1) throw new Error(MULTI_CHAPTER_ERROR)
}

export function douyinXianjieChapter(sourceText = '') {
  const text = String(sourceText)
  assertDouyinXianjieSingleChapterSource(text)
  const hasProjectCue = /林夜|抖音|姹女教|白清玄|天机一型|手机/u.test(text)
  const hasChapter1SystemCue = /神级文娱系统|系统绑定|抖音纯享版|天机一型|手机|商城/u.test(text)

  if (/第1章/u.test(text)) return 1
  if (/第2章/u.test(text)) return 2
  if (/第3章/u.test(text) && hasProjectCue) return 3

  if (hasProjectCue && /旗袍|JK|高跟鞋|抖音教学玉简|拉黑是什么意思|拉黑|每人每日|每日不少于|换装/u.test(text)) return 3
  if (/姹女教|白清玄|幽冥虎王|一万部手机|招募女主播|专程来找|双修|能歌善舞/u.test(text)) return 2
  if (hasChapter1SystemCue && /林夜|鬼王宗|神级文娱系统|天机一型/u.test(text)) return 1

  return null
}

export function isDouyinXianjieOpeningSource(sourceText = '') {
  return douyinXianjieChapter(sourceText) !== null
}

export function douyinXianjieStyle(style) {
  const clean = compact(style)
  if (!clean) return DEFAULT_STYLE
  if (/3D国漫|国漫|仙侠/u.test(clean)) return clean
  return `${DEFAULT_STYLE}，${clean}`
}

export function douyinXianjieTitle(sourceText = '') {
  const chapter = douyinXianjieChapter(sourceText)
  if (chapter === 1) return '抖音仙界第1章｜神级文娱系统'
  if (chapter === 2) return '抖音仙界第2章｜抖音，招募女主播'
  if (chapter === 3) return '抖音仙界第3章｜旗袍，JK'
  return '抖音仙界开局'
}

export function douyinXianjieFeedFileName(sourceText = '') {
  const chapter = douyinXianjieChapter(sourceText)
  if (chapter === 1) return 'seedance-all-reference-feed-01.md'
  if (chapter === 2) return 'seedance-all-reference-feed-02.md'
  if (chapter === 3) return 'seedance-all-reference-feed-03.md'
  return 'seedance-all-reference-feed.md'
}

