function finishPrompt(prompt) {
  return String(prompt ?? '').trim().replace(/[。！!]*$/u, '') + '。4K画质！'
}

function characterPrompt({ base, name, details }) {
  const safeDetails = appendFemaleXianxiaSafeguard(details, { name, sourceText: details, style: base })
  return finishPrompt([
    `${base}【三视图生成模板】设计3D国漫人物三视图：${name}，正面全身照、侧面全身照、背面全身照，最左侧单独的上半身+头部细节展示，背景为白色或极浅灰色，整体构图工整专业。三视图为一张图。`,
    `角色设定：${safeDetails}`,
    '四个展示区必须属于同一个角色，同一张脸、同一发型、同一体型、同一服装、同一配饰。脸部必须有柔和电影面光，眼睛有清晰高光。',
    '不要剧情动作，不要复杂场景，不要多人，不要换装，不要文字水印。'
  ].join(''))
}

